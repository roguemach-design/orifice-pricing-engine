"""Owner-approved PDF adapter: legacy compatibility and v4 tamper rejection."""

from dataclasses import replace
from io import BytesIO
from pathlib import Path
import json

import pytest
from pypdf import PdfReader, PdfWriter
from pypdf.generic import DecodedStreamObject, NameObject

from frozen_plate.validation import validate_package
from manufacturing_context import DrawingState
from manufacturing_drawing import DrawingMetadata
from manufacturing_files import generate_package
from plate_geometry import build_plate_geometry
from prototype_manufacturing import sample_spec


def package(tmp_path, *, hole=True, part="PROTOTYPE-001"):
    spec = replace(
        sample_spec(), part_identifier=part,
        handle_hole_enabled=hole,
        handle_hole_diameter=.375 if hole else None,
        handle_hole_center_from_handle_end=.75 if hole else None,
    )
    g = build_plate_geometry(spec)
    metadata = DrawingMetadata(
        revision="R1", state=DrawingState.CUSTOMER_CONFIRMATION,
        specification_revision="R1", order_line_revision="L1-R1",
        order_identifier="TEST-VALIDATOR",
    )
    outputs = generate_package(g, tmp_path, metadata=metadata, include_svg=False)
    return g, metadata, outputs


def alter_pdf(raw, *, replacement=None, subject=None):
    reader = PdfReader(BytesIO(raw))
    writer = PdfWriter(clone_from=reader)
    if replacement:
        old, new = replacement
        data = writer.pages[0].get_contents().get_data()
        assert old in data, "tamper target must exist in the real PDF stream"
        changed = DecodedStreamObject()
        changed.set_data(data.replace(old, new))
        writer.pages[0][NameObject("/Contents")] = writer._add_object(changed)
    if subject is not None:
        writer.add_metadata({"/Subject": subject})
    output = BytesIO()
    writer.write(output)
    return output.getvalue()


@pytest.mark.parametrize("hole", [False, True])
@pytest.mark.parametrize("part", ["PROTOTYPE-001", "PRD-a04088158d8767b4-1", "OP-TEST-001"])
def test_v4_package_accepts_exact_provenance_and_visible_requirements(tmp_path, hole, part):
    validate_package(*package(tmp_path, hole=hole, part=part))


@pytest.mark.parametrize("hole", [False, True])
def test_v3e_actual_base_renderer_bytes_remain_accepted(tmp_path, hole):
    # Generated with the unchanged 34707eb renderer; never regenerated by v4.
    g, metadata, outputs = package(tmp_path, hole=hole)
    name = "legacy-v3e-hole.pdf" if hole else "legacy-v3e.pdf"
    outputs["pdf"] = (Path(__file__).parent / "fixtures" / name).read_bytes()
    validate_package(g, metadata, outputs)


@pytest.mark.parametrize("field,value", [
    ("part", "PROTOTYPE-999"), ("order", "TEST-OTHER"),
    ("geometry", "other-geometry"), ("state", "released-for-manufacture"),
    ("generator", "op-drawing-v3e"),
])
def test_v4_rejects_wrong_exact_provenance(tmp_path, field, value):
    g, metadata, outputs = package(tmp_path)
    provenance = json.loads(PdfReader(BytesIO(outputs["pdf"])).metadata.subject)
    provenance[field] = value
    outputs["pdf"] = alter_pdf(outputs["pdf"], subject=json.dumps(provenance))
    with pytest.raises(ValueError, match="provenance"):
        validate_package(g, metadata, outputs)


@pytest.mark.parametrize("subject", ["", "not-json", "null", "[]"])
def test_v4_missing_or_malformed_provenance_cannot_fall_back_to_legacy(tmp_path, subject):
    g, metadata, outputs = package(tmp_path)
    outputs["pdf"] = alter_pdf(outputs["pdf"], subject=subject)
    with pytest.raises(ValueError, match="provenance"):
        validate_package(g, metadata, outputs)


@pytest.mark.parametrize("replacement", [
    (b"1.548", b"1.549"), (b"5.000", b"5.001"),
    (b"10.50", b"10.51"), (b"2.00", b"2.01"),
    (b".125", b".126"), (b".375 THRU", b".376 THRU"),
    (b"(.75)", b"(.76)"), (b"OP-SAMPLE-001", b"OP-SAMPLE-999"),
    (b"(R1)", b"(R2)"), (b"LINE L1-R1", b"LINE L1-R2"),
    (b"CUSTOMER CONFIRMATION", b"MANUFACTURE RELEASE"),
])
def test_v4_rejects_changed_visible_requirements_even_with_correct_provenance(tmp_path, replacement):
    g, metadata, outputs = package(tmp_path)
    outputs["pdf"] = alter_pdf(outputs["pdf"], replacement=replacement)
    with pytest.raises(ValueError, match="PDF missing"):
        validate_package(g, metadata, outputs)


def test_v4_short_identifier_collision_does_not_mask_different_full_identity(tmp_path):
    g, metadata, outputs = package(tmp_path, part="PRD-a04088158d8767b4-1")
    _, _, other = package(tmp_path / "other", part="PRD-a0408815ffffffff-1")
    outputs["pdf"] = other["pdf"]
    with pytest.raises(ValueError, match="provenance"):
        validate_package(g, metadata, outputs)


def test_v3e_still_rejects_changed_handle_hole_callout(tmp_path):
    g, metadata, outputs = package(tmp_path)
    raw = (Path(__file__).parent / "fixtures/legacy-v3e-hole.pdf").read_bytes()
    outputs["pdf"] = alter_pdf(raw, replacement=(b"0.3750", b"0.3760"))
    with pytest.raises(ValueError, match="handle hole requirement"):
        validate_package(g, metadata, outputs)
