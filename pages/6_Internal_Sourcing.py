"""Owner review of the accepted immutable Frozen Plate records; API authorization is mandatory."""

import os
from hashlib import sha256
import requests
import streamlit as st
from frozen_plate.runtime import ui_enabled

st.set_page_config(page_title="O-Plates — Orders & Manufacturing", layout="wide")
API = os.environ.get("API_BASE", "").rstrip("/")
if not ui_enabled():
    st.error("Owner portal production binding is unavailable.")
    st.stop()
st.title("O-Plates — Orders & Manufacturing")
st.caption(
    "Owner-only review. Vendor submission and manufacturing release are disabled. Recorded sourcing routes are informational only."
)
key = st.text_input(
    "Internal admin credential", type="password", key="owner_admin_credential"
)
if not key:
    st.info("Enter your existing internal admin credential to review orders.")
    st.stop()
headers = {"x-api-key": key}


def call(path, **kwargs):
    try:
        response = requests.get(API + path, headers=headers, timeout=120, **kwargs)
    except requests.RequestException:
        st.error("Production service unavailable.")
        st.stop()
    if response.status_code != 200:
        st.error(
            "Request unavailable. Check owner authorization and the selected revision."
        )
        st.stop()
    return response


def exact_download(rev, kind, path, label):
    response = call(path)
    artifact = rev["artifacts"][kind]
    if (
        sha256(response.content).hexdigest() != artifact["sha256"]
        or len(response.content) != artifact["size"]
    ):
        st.error("Artifact integrity mismatch. Download blocked.")
        st.stop()
    st.download_button(
        label,
        response.content,
        file_name=artifact["filename"],
        mime={
            "pdf": "application/pdf",
            "json": "application/json",
            "dxf": "application/dxf",
        }[kind],
        key=kind + "-" + rev["id"],
    )


orders = call("/admin/orders", params={"limit": 200}).json()
completed = [o for o in orders if o["status"] == "completed"]
inventory = call("/admin/frozen-plates").json()
labels = {
    o["id"]: f"{o['order_number_display'] or o['id']} · {o.get('payment_mode', 'UNKNOWN')} · {o['created_at']}"
    for o in completed
}
for plate in inventory:
    labels.setdefault(plate["order_id"], "Frozen Plate record · " + plate["order_id"])
if not labels:
    st.info("No completed orders or Frozen Plate records.")
    st.stop()
order_id = st.selectbox(
    "Completed order or Frozen Plate record", list(labels), format_func=labels.get
)
if order_id in {o["id"] for o in completed}:
    order = call(f"/admin/orders/{order_id}").json()
    if order.get("payment_mode") == "OWNER TEST":
        st.info("TEST ORDER — sandbox payment. Review only; no manufacturing release or vendor submission.")
    with st.expander("Order and line-item record"):
        st.json(order)
else:
    st.info(
        "Existing Frozen Plate verification record; no matching completed order-table row."
    )
plates = call("/admin/frozen-plates", params={"order_id": order_id}).json()
if not plates:
    st.info(
        "No Frozen Plate record is available for this order. No artifacts are generated by this review portal."
    )
for plate in plates:
    st.subheader(f"{plate['line_id']} · {plate['lifecycle']}")
    revisions = call(f"/admin/frozen-plates/{plate['id']}/revisions").json()
    if not revisions:
        st.warning("No complete drawing revision.")
        continue
    revision_id = st.selectbox(
        "Immutable revision",
        [r["id"] for r in revisions],
        format_func=lambda rid: next(
            f"R{r['number']} · {'Current' if rid == plate['current_revision'] else 'Superseded'}"
            for r in revisions
            if r["id"] == rid
        ),
        key="revision-" + plate["id"],
    )
    detail = call(
        f"/admin/frozen-plates/{plate['id']}", params={"revision_id": revision_id}
    ).json()
    rev = detail["revision"]
    current = rev["id"] == plate["current_revision"]
    st.write(f"Plate {plate['id']} · R{rev['number']} · {rev['id']}")
    st.code("Spec SHA-256: " + rev["spec_sha256"], language=None)
    st.dataframe(
        [
            {
                "Kind": kind,
                "Filename": a["filename"],
                "Bytes": a["size"],
                "SHA-256": a["sha256"],
            }
            for kind, a in rev["artifacts"].items()
        ],
        hide_index=True,
    )
    exact_download(
        rev,
        "pdf",
        f"/admin/frozen-plates/revisions/{rev['id']}/artifact/pdf",
        "Download exact finished-part PDF",
    )
    exact_download(
        rev,
        "json",
        f"/admin/frozen-plates/revisions/{rev['id']}/artifact/json",
        "Download exact internal spec record",
    )
    approved = any(
        a["pdf_sha256"] == rev["artifacts"]["pdf"]["sha256"]
        and a["spec_sha256"] == rev["spec_sha256"]
        for a in detail["approvals"]
    )
    if approved:
        st.success(
            "Current revision approved"
            if current
            else "Historical approval — superseded revision"
        )
        if current:
            exact_download(
                rev,
                "dxf",
                f"/admin/frozen-plates/revisions/{rev['id']}/dxf",
                "Download exact approved rough-blank DXF",
            )
    else:
        st.info("Revision is not approved. DXF download remains blocked.")
    if not current:
        st.info("Superseded immutable revision. DXF download and sourcing are blocked.")
    with st.expander("Approval, delivery and sourcing evidence"):
        st.json(
            {
                "approvals": detail["approvals"],
                "deliveries": detail["deliveries"],
                "sourcing": detail["sourcing"],
            }
        )
        st.json(call(f"/admin/frozen-plates/revisions/{rev['id']}/email-status").json())
        st.caption(
            "Sourcing routes: SENDCUTSEND · ALRO · ROGUE_INTERNAL. Review only; no route changes, vendor transmission, CNC job or manufacturing release."
        )
        for delivery in detail["deliveries"]:
            if st.button("Load captured confirmation", key="capture-" + delivery["id"]):
                eml = call(
                    "/admin/frozen-plates/deliveries/" + delivery["id"] + "/capture"
                ).content
                st.download_button(
                    "Download captured email",
                    eml,
                    file_name="confirmation.eml",
                    mime="message/rfc822",
                    key="eml-" + delivery["id"],
                )
